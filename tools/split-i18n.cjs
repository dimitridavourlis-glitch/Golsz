// SHIP ONE LANGUAGE, NOT FOUR.
//
// golsz-app.html declares all four dictionaries in one I18N object, so every
// athlete downloads French, Spanish and Greek to read English. Measured on the
// compiled bundle at 2b44ac2 by gzipping it with and without them:
//
//     all four languages   336,142 bytes gzipped
//     English only         266,838 bytes gzipped
//     marginal cost         69,304 bytes  (20.6% of the bundle)
//
// gzip does not collapse them the way you might hope - they are similar in
// shape but share almost no literal text.
//
// WHY THIS IS A BUILD STEP, like tools/strip-jsx.cjs.
// Those dictionaries are the source: every i18n suite asserts key parity,
// interpolation parity and duplicate-freedom against golsz-app.html. Removing
// them from the repo would blind all of it. So the repo keeps four and the
// deploy ships one, plus three files fetched only by the athletes who need them.
//
// WHAT MAKES IT SAFE.
// The runtime already degrades correctly: `t` falls back to I18N.en for any
// key whose language is absent (golsz-app.html, `const t = (key) => ...`), and
// the loader calls loadApp() on the dictionary's onerror as well as its onload.
// So the worst case is a working app in English, never a blank screen and
// never raw key names.
//
// Usage: node tools/split-i18n.cjs [htmlPath] [outDir]
// Defaults to the repo's own files; the test passes copies.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const HTML = process.argv[2] || path.join(ROOT, "golsz-app.html");
const OUTDIR = process.argv[3] || path.join(ROOT, "js", "i18n");

// English stays in the bundle: it is the fallback every other language leans
// on, so it must be present before any dictionary has had a chance to load.
const LIFTED = ["fr", "es", "el"];

const html = fs.readFileSync(HTML, "utf8");

if (html.indexOf("\n  fr: {\n") < 0) {
  console.log("split: no lifted dictionaries present, nothing to do");
  process.exit(0);
}

// The merge hook has to exist, or the lifted dictionaries would be written to
// a global nothing ever reads and three languages would silently become
// English. Refuse rather than ship that.
if (html.indexOf("Object.assign(I18N, (typeof window !== \"undefined\" && window.__GOLSZ_I18N) || {});") < 0) {
  console.error("split: golsz-app.html has no __GOLSZ_I18N merge hook — refusing to lift dictionaries nothing would read");
  process.exit(1);
}

let out = html;
const written = [];

for (const lang of LIFTED) {
  const open = "\n  " + lang + ": {\n";
  const i = out.indexOf(open);
  if (i < 0) {
    console.error("split: could not find the " + lang + " dictionary");
    process.exit(1);
  }
  const bodyStart = i + open.length;
  // Each dictionary is a run of very long lines closed by a `  },` at the same
  // indent. Bounded by that rather than by a character count, because a fixed
  // window is exactly how this file's own i18n tests once spilled one language
  // into the next.
  const close = out.indexOf("\n  },\n", bodyStart);
  if (close < 0) {
    console.error("split: the " + lang + " dictionary has no closing brace");
    process.exit(1);
  }
  const body = out.slice(bodyStart, close);
  if (!/\w+:\s*"/.test(body)) {
    console.error("split: the " + lang + " block does not look like a dictionary — refusing");
    process.exit(1);
  }

  fs.mkdirSync(OUTDIR, { recursive: true });
  const file = path.join(OUTDIR, lang + ".js");
  fs.writeFileSync(file,
    "// GENERATED by tools/split-i18n.cjs — do not edit.\n" +
    "// Source of truth is the " + lang + " dictionary in golsz-app.html.\n" +
    "window.__GOLSZ_I18N = window.__GOLSZ_I18N || {};\n" +
    "window.__GOLSZ_I18N." + lang + " = {\n" + body + "\n};\n");
  written.push({ lang, file, bytes: body.length });

  out = out.slice(0, i) + out.slice(close + "\n  },".length);
}

// What is left must still be a dictionary object with English in it.
if (out.indexOf("\n  en: {\n") < 0) {
  console.error("split: English is missing from the reduced source — refusing to write");
  process.exit(1);
}
for (const lang of LIFTED) {
  if (out.indexOf("\n  " + lang + ": {\n") > -1) {
    console.error("split: " + lang + " survived the lift — refusing to write a half-split file");
    process.exit(1);
  }
}

fs.writeFileSync(HTML, out);
const saved = html.length - out.length;
console.log("split: lifted " + written.map((w) => w.lang).join(", ") +
  " (" + saved + " chars) to " + path.relative(ROOT, OUTDIR) + "/");
for (const w of written) console.log("  " + w.lang + ".js  " + w.bytes + " chars");
console.log("split: run `npm run compile` next so js/app.js is rebuilt without them");
