// THE SHIPPED BUNDLE IS MINIFIED, AND STILL DIAGNOSABLE.
//
// js/app.js was 1.18 MB (about 352 KB gzipped) because Babel compiles JSX but
// does not compress it. tools/precompile.cjs now minifies with terser. What has
// to stay true, and what this holds:
//   * it is actually smaller (a silently disabled minifier would pass every
//     other suite)
//   * top-level names survive: golsz-app.html's loader and tests refer to
//     globals the bundle defines
//   * component and function names survive, so a stack in a support email or
//     the render-crash boundary's log still says which screen failed
//   * the source-sha stamp is still the first thing strip-jsx.cjs reads
//   * no source map reference points at a file that is not deployed

const fs = require("fs");
const path = require("path");
const REPO = path.join(__dirname, "..");
const APPJS = fs.readFileSync(path.join(REPO, "js", "app.js"), "utf8");
const PRE = fs.readFileSync(path.join(REPO, "tools", "precompile.cjs"), "utf8");

let p = 0, f = 0;
const ck = (l, a, e) => {
  const ok = JSON.stringify(a) === JSON.stringify(e);
  if (ok) p++; else { f++; console.log(`FAIL  ${l}\n      got:      ${JSON.stringify(a)}\n      expected: ${JSON.stringify(e)}`); }
};

ck("the bundle is under 900 KB (it was 1.18 MB before minifying)", APPJS.length < 900000, true);
ck("...and not suspiciously tiny (that would be truncation, not minification)", APPJS.length > 400000, true);
ck("it is not formatted: a line is long, not one statement per line", APPJS.split("\n").length < 50, true);
ck("the source-sha stamp is still in the first lines", /^\/\/ source-sha: [0-9a-f]{16}$/m.test(APPJS.split("\n").slice(0, 4).join("\n")), true);
ck("the GENERATED / DO NOT EDIT header survives", /^\/\/ GENERATED by tools\/precompile\.cjs/.test(APPJS), true);

for (const name of ["GolszApp", "AdminPanel", "AdminMfa", "SettingsButton", "Auth", "CheckoutReturnBanner", "Passport"]) {
  ck(`component ${name} keeps its name (stacks stay readable)`, new RegExp(`function ${name}\\(`).test(APPJS), true);
}
for (const global of ["I18N", "PLANS", "PASSWORD_MIN", "safeHref", "asButton", "signupErrorKey", "formatBillingDate"]) {
  ck(`top-level ${global} keeps its name (loader and other code refer to globals)`, new RegExp(`\\b${global}\\b`).test(APPJS), true);
}
ck("React.createElement is intact (the react preset ran, the minifier did not eat it)", /React\.createElement/.test(APPJS), true);
ck("no source map is referenced", /sourceMappingURL/.test(APPJS), false);

// The configuration, so a "simplification" cannot quietly turn on the options
// that break a classic script.
ck("terser is applied inside compile(), so the committed bundle and the Vercel rebuild are the same kind of file", /return minify\(code\);/.test(PRE), true);
ck("mangling of top-level names is NOT enabled", /toplevel\s*:\s*true/.test(PRE), false);
ck("function names are kept", /keep_fnames: true/.test(PRE), true);
ck("it fails loudly if the minifier returns nothing", /terser produced no output/.test(PRE), true);
ck("terser is a pinned dev dependency (the Vercel build installs it)", /"terser": "5\.\d+\.\d+"/.test(fs.readFileSync(path.join(REPO, "package.json"), "utf8")), true);

console.log(`\n${p}/${p + f} passed`);
process.exit(f ? 1 : 0);
